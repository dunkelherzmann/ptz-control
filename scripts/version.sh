#!/bin/sh
# Prints the app version: the major.minor in VERSION, then the number of commits since VERSION last
# changed, so every push to main raises it (1.0.1, 1.0.2, …) and editing VERSION to 1.1 starts at 1.1.0.
# With --header it also writes core/include/ptz_version.h, which every platform's build compiles in.
# Without git history (a source download, a shallow clone) the patch number is 0.
set -eu
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
BASE="$(tr -d ' \n\r' < "$ROOT/VERSION")"
PATCH=0
if since="$(git -C "$ROOT" log -1 --format=%H -- VERSION 2>/dev/null)" && [ -n "$since" ]; then
    PATCH="$(git -C "$ROOT" rev-list --count "$since..HEAD")"
fi
VERSION="$BASE.$PATCH"
if [ "${1:-}" = "--header" ]; then
    MAJOR="${BASE%%.*}"
    MINOR="${BASE#*.}"
    cat > "$ROOT/core/include/ptz_version.h.tmp" <<HEADER
/* Generated by scripts/version.sh; not tracked by git. */
#define PTZ_VERSION "$VERSION"
#define PTZ_VERSION_MAJOR $MAJOR
#define PTZ_VERSION_MINOR $MINOR
#define PTZ_VERSION_PATCH $PATCH
HEADER
    # Rewritten only when the version changes, so builds don't recompile for nothing.
    if cmp -s "$ROOT/core/include/ptz_version.h.tmp" "$ROOT/core/include/ptz_version.h"; then
        rm "$ROOT/core/include/ptz_version.h.tmp"
    else
        mv "$ROOT/core/include/ptz_version.h.tmp" "$ROOT/core/include/ptz_version.h"
    fi
fi
printf '%s\n' "$VERSION"
