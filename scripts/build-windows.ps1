# Builds dist\PTZControl.exe (Windows 10/11 x64) on Windows with the Visual Studio C++ Build Tools
# (MSVC). Fully static (/MT): one portable .exe that imports only Windows system DLLs, no installer,
# no administrator rights.
# Usage: powershell -ExecutionPolicy Bypass -File scripts\build-windows.ps1 [-Zip]
param([switch]$Zip)
$ErrorActionPreference = 'Stop'

$Root = Split-Path -Parent $PSScriptRoot
$Obj = Join-Path $Root '.build\windows'
$Dist = Join-Path $Root 'dist'
New-Item -ItemType Directory -Force $Obj, $Dist | Out-Null

# Version: the same rule as scripts/version.sh (major.minor from VERSION, patch = commits since
# VERSION last changed, 0 without git history), written to core\include\ptz_version.h.
$Base = (Get-Content -Raw (Join-Path $Root 'VERSION')).Trim()
$Patch = 0
$since = $null
try { $since = git -C $Root log -1 --format=%H -- VERSION 2>$null } catch { }
if ($since) { $Patch = [int](git -C $Root rev-list --count "$since..HEAD") }
$Major, $Minor = $Base.Split('.')
$Version = "$Base.$Patch"
$header = "/* Generated by scripts/version.sh; not tracked by git. */`n" +
          "#define PTZ_VERSION `"$Version`"`n#define PTZ_VERSION_MAJOR $Major`n" +
          "#define PTZ_VERSION_MINOR $Minor`n#define PTZ_VERSION_PATCH $Patch`n"
$headerPath = Join-Path $Root 'core\include\ptz_version.h'
# Rewritten only when the version changes, so builds don't recompile for nothing.
if (-not (Test-Path $headerPath) -or (Get-Content -Raw $headerPath) -ne $header) {
    [IO.File]::WriteAllText($headerPath, $header)
}
Write-Output "PTZ Control $Version"

# The x64 compiler environment of the newest Visual Studio (or Build Tools) with the C++ workload.
$vswhere = Join-Path ${env:ProgramFiles(x86)} 'Microsoft Visual Studio\Installer\vswhere.exe'
if (-not (Test-Path $vswhere)) { throw 'Visual Studio Build Tools not found; install them with the "Desktop development with C++" workload' }
$vs = & $vswhere -latest -products * -requires Microsoft.VisualStudio.Component.VC.Tools.x86.x64 -property installationPath
if (-not $vs) { throw 'No Visual Studio installation has the C++ x64 tools ("Desktop development with C++")' }
$vcvars = Join-Path $vs 'VC\Auxiliary\Build\vcvars64.bat'
cmd /c "`"$vcvars`" >nul && set" | ForEach-Object {
    if ($_ -match '^([^=]+)=(.*)$') { Set-Item -Path "env:$($Matches[1])" -Value $Matches[2] }
}
if (-not (Get-Command cl.exe -ErrorAction SilentlyContinue)) { throw "cl.exe not found after $vcvars" }

function Invoke-Tool([string]$tool, [string[]]$arguments) {
    & $tool @arguments
    if ($LASTEXITCODE -ne 0) { throw "$tool failed ($LASTEXITCODE)" }
}

$flags = @('/nologo', '/std:c++20', '/O2', '/MT', '/EHsc', '/utf-8', '/permissive-', '/W3', '/Gy', '/Gw',
           '/DUNICODE', '/D_UNICODE', '/DNOMINMAX', '/D_WIN32_WINNT=0x0A00',
           '/DWINVER=0x0A00', '/D_CRT_SECURE_NO_WARNINGS', "/I$Root\core\include")
$objects = @()
foreach ($src in (Get-ChildItem "$Root\core\src\*.cpp", "$Root\windows\src\*.cpp")) {
    $o = Join-Path $Obj ($src.BaseName + '.obj')
    Write-Output "Compiling $($src.FullName.Substring($Root.Length + 1))"
    Invoke-Tool cl.exe ($flags + @('/c', $src.FullName, "/Fo$o"))
    $objects += $o
}

# Icon, manifest and version information (windows\res\app.rc; app.ico has the macOS app's artwork).
$res = Join-Path $Obj 'app.res'
Invoke-Tool rc.exe @('/nologo', "/I$Root\windows\res", "/I$Root\core\include", "/fo$res", "$Root\windows\res\app.rc")

$exe = Join-Path $Dist 'PTZControl.exe'
Invoke-Tool link.exe ($objects + @($res, '/nologo', "/OUT:$exe", '/SUBSYSTEM:WINDOWS', '/MACHINE:X64',
    '/OPT:REF', '/OPT:ICF', '/MANIFEST:NO', '/INCREMENTAL:NO',
    'winhttp.lib', 'ws2_32.lib', 'bcrypt.lib', 'gdiplus.lib', 'comctl32.lib', 'dwmapi.lib', 'uxtheme.lib',
    'shell32.lib', 'advapi32.lib', 'gdi32.lib', 'user32.lib', 'ole32.lib'))
Write-Output 'Built dist\PTZControl.exe'

if ($Zip) {
    $archive = Join-Path $Dist "PTZ-Control-$Version-Windows-x64.zip"
    Remove-Item -Force -ErrorAction SilentlyContinue $archive
    Compress-Archive -Path $exe -DestinationPath $archive
    Write-Output "Zipped dist\PTZ-Control-$Version-Windows-x64.zip"
}
